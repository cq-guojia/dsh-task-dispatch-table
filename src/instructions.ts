/**
 * 派发给执行 agent 的指令文本 —— **唯一真源**。
 *
 * 此前同一套规则分散在四个指令面：工具 `description`（常驻上下文）、`receiptInstruction`
 * （派发消息最末「唯一权威段」，缺回执追问复用）、`buildMessage` 的【执行约束】、
 * `/goal` objective。各写一份必然漂移，真机上已发生过两次：
 *   · 产出粒度在 description 里有三条细则，权威段却只剩一句压缩句 ⇒ 模型按最弱的一处
 *     遵守（`receipt.ts` 历史注释原话），`processOutputs` 退化成逐文件列；
 *   · 无人值守约束只进派发段，追问轮（伪装成 `role:'user'`）与 goal 续跑轮读不到。
 *
 * 本模块只导出常量与纯函数，四个面只做引用；冒烟断言钉「引用了同一常量」而非钉原话，
 * 因此以后调整文案不会再打掉断言（`ledger/worklog/202610/10-0000-…270e.md` 记过这个教训）。
 */

/**
 * 无人值守约束。派发消息、缺回执追问、`/goal` objective 三处必须逐字引用同一份。
 */
export const UNATTENDED_RULE =
  '【执行约束】本任务是定时自动派发、无人值守运行的：执行期间没有人会回复你。'
  + '因此：① 不得向用户提问或等待答复——信息不足就基于现有上下文自行决策并继续，必要时在回执 note 中如实记录；'
  + '② 不得申请、索取或等待任何额外权限或授权——严格在已授予的权限范围内执行，超范围的操作跳过并在回执中说明，不要停下来要许可。'

/**
 * 缺回执追问走 `userNotice`，生成的是 `role:'user'` 消息 —— 模型会误以为有人回复了。
 * 追问必须先声明身份，再复述 {@link UNATTENDED_RULE}。
 */
export const NUDGE_NOTICE =
  '【系统自动追问】这条消息由插件在会话结束后自动发出，不是用户回复；本任务仍然无人值守，'
  + '不得提问、不得等待答复或授权。'

/**
 * 产出两桶的申报口径与粒度规则。
 *
 * 工具 `description` 与 `receiptInstruction` 的「唯一权威段」必须引用**同一份返回值**，
 * 避免再出现「一处全集、一处摘要」的强弱差。
 *
 * 规则按①→②→③写成可终止的判定顺序：把「只有…才逐个列文件」从段末唯一许可
 * 降级成第③步兜底分支，并给正反例；`web-app/` 与按日期归档两个误导锚点已删除。
 *
 * @param maxItems 每桶上限（`receipt.ts` 的 `MAX_OUTPUT_ITEMS`），不在本模块另写数字。
 * @param toolName 回执工具名（`receipt.ts` 的 `RECEIPT_TOOL_NAME`），用于正例的调用形状。
 */
export function outputRules(maxItems: number, toolName: string): string {
  return [
    `- 产出分两桶报：**主文件**填 outputs（最终交付物），**其他产出**填 processOutputs（日志 / 中间产物 / 工作目录）；`
      + `各不超过 ${maxItems} 项，**一个目录只算 1 项**（里面几百个文件也是 1 项）；没有主文件就省略 outputs。`,
    '- 怎么交（按①→②→③照做，两桶都适用，outputs 与 processOutputs 都一样）：',
    '① 先找「**专为本任务新建、且只放本任务内容**」的目录（手册建目录脚本建的、目录名带本任务标识；父目录是共用归档或路径带日期层级，都不改变它是专属目录）。',
    '② 找到 ⇒ **整目录报路径（相对工作区根、结尾带 "/"，有几个报几个、每个 1 项），到此为止**：'
      + '整个目录本身就是交付物就填 outputs；否则 outputs 只填目录里那个主文件（没有主文件就省略）、processOutputs 填**整个目录**。'
      + '**不要列目录内的文件名**（raw.json / err.txt / stack.json 之类一律不单列）；'
      + '「主文件在 outputs、其父目录在 processOutputs」**含纳关系合法，不冲突**，不要为了避嫌去拆分、挪动文件再整理。',
    '③ 没找到专属目录、文件散落在既有 / **共用目录**里 ⇒ 才逐个列文件。',
    '- 正例（照这个形状填）：目录 <任务目录>/ 里有 report.md（主文件）+ raw.json / err.txt（中间） ⇒ '
      + `${toolName}({ status: "<合法值>", outputs: ["<任务目录>/report.md"], processOutputs: ["<任务目录>/"] })。`,
    '- 反例（禁止）：processOutputs: ["<任务目录>/raw.json", "<任务目录>/err.txt"] —— 即使目录名带日期、父目录是共用归档，也不许拆成单文件。',
    `- 两个桶都可以空，但回执本身必须交（没有产出就省略它们）；note **只写说明**（失败原因 / 关键结论），不写路径、不用来补列文件。`,
    '- **以最后一次提交为准**：重复提交会整体覆盖；再次提交时两桶先前报过的**路径项**原样回带（**一并带上**，不回带 = 放弃）——'
      + '整目录那 1 项照原样回带，不是补列文件名。',
    `补充：超出 ${maxItems} 项只记前 ${maxItems} 项，同一路径只报一次、别重复；`
      + '只是跑出了一堆过程、没有最终交付物 ⇒ 省略 outputs，不要把其他产出塞进来；③ 里没有专属目录时才按文件逐个列。',
  ].join('\n')
}
